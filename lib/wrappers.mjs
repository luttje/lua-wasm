// Turns the Lua API description from lua-api.mjs into build inputs:
// C wrappers that make macros exportable, and type metadata for JavaScript.

// Macros that only work on literals, so a function taking a variable in
// their place would compile but misbehave.
const NEEDS_LITERAL_ARGUMENT = new Set([
  'lua_pushliteral', // concatenates its argument with "" at compile time
  'luaL_newlib', // takes sizeof() of the array passed to it
  'luaL_newlibtable',
])

function reasonNotWrappable(macro) {
  if (NEEDS_LITERAL_ARGUMENT.has(macro.name)) return 'only works on a literal argument'
  if (macro.isVariadic) return 'takes a variable number of arguments'
  if (macro.parameters.some((parameter) => parameter.type === null)) return 'is type-generic'
  if (macro.parameters.some((parameter) => parameter.isArray)) return 'takes an array'

  return null
}

function declareParameters(parameters) {
  if (parameters.length === 0) return 'void'

  return parameters.map(({ type, name }) => (type.endsWith('*') ? `${type}${name}` : `${type} ${name}`)).join(', ')
}

function declare(returnType, name, parameters) {
  const separator = returnType.endsWith('*') ? '' : ' '

  return `${returnType}${separator}${name}(${declareParameters(parameters)})`
}

/**
 * Generates a C file that defines a real function for every macro in the
 * API, under the macro's own name.
 *
 * WebAssembly can only export symbols, and a macro such as `lua_pcall` is
 * gone after preprocessing. So each macro is first captured in a static
 * helper while it is still defined, then removed with #undef, and finally
 * a function with the documented name forwards to the helper. All helpers
 * come before the first #undef because macros may expand to other macros.
 *
 * Returns the C source, the entries that were wrapped and those skipped.
 */
export function generateMacroWrappers(api) {
  const wrapped = []
  const skipped = []

  for (const entry of api) {
    if (entry.kind !== 'macro') continue

    const reason = reasonNotWrappable(entry)

    if (reason) skipped.push({ name: entry.name, reason })
    else wrapped.push(entry)
  }

  const helpers = wrapped.map(({ name, returnType, parameters }) => {
    const call = `${name}(${parameters.map((parameter) => parameter.name).join(', ')})`
    const body = returnType === 'void' ? `${call};` : `return ${call};`

    return `static ${declare(returnType, `wasm__${name}`, parameters)} { ${body} }`
  })

  const undefs = wrapped.map(({ name }) => `#undef ${name}`)

  const functions = wrapped.map(({ name, returnType, parameters }) => {
    const call = `wasm__${name}(${parameters.map((parameter) => parameter.name).join(', ')})`
    const body = returnType === 'void' ? `${call};` : `return ${call};`

    return `${declare(returnType, name, parameters)} { ${body} }`
  })

  const source = `/* Generated by lua-wasm. Do not edit: changes are overwritten on every build. */

#include <stddef.h>

#include "lua.h"
#include "lauxlib.h"
#include "lualib.h"

/* 1. Capture every macro while it is still defined. */
${helpers.join('\n')}

/* 2. Remove the macros, freeing up their names. */
${undefs.join('\n')}

/* 3. Define real functions under those names. */
${functions.join('\n')}
`

  return { source, wrapped, skipped }
}

function toJsType(cType) {
  if (cType === 'void') return null
  if (/^const char \*$/.test(cType)) return 'string'

  return 'number'
}

/**
 * Describes each entry for Emscripten's `cwrap(name, returnType, parameterTypes)`.
 * Variadic functions only list their fixed parameters.
 */
export function describeBindings(entries) {
  const bindings = {}

  for (const { name, returnType, parameters } of entries) {
    bindings[name] = {
      returnType: toJsType(returnType),
      parameterTypes: parameters.map((parameter) => toJsType(parameter.type)),
    }
  }

  return bindings
}

/**
 * Generates the JavaScript that emcc runs inside the module (`--post-js`).
 * It puts every function in `bindings` on the module under its C name, so
 * users call `lua.lua_gettop(L)` instead of wrapping functions themselves.
 * cwrap only works once the WebAssembly is ready, so each function wraps
 * itself on its first call.
 */
export function generateBindingsScript(bindings) {
  return `// Generated by lua-wasm. Do not edit: changes are overwritten on every build.
for (const [name, { returnType, parameterTypes }] of Object.entries(${JSON.stringify(bindings)})) {
  let wrapped;
  Module[name] = (...args) => {
    if (!wrapped) wrapped = cwrap(name, returnType, parameterTypes);
    return wrapped(...args);
  };
}
`
}
